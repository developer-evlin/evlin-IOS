import Foundation
import SwiftUI

@MainActor
class AppSync {
    static let shared = AppSync()
    
    // Call this when the app starts or comes foreground, and after onboarding finishes
    func syncBackendData() async {
        do {
            let apiChildren = try await APIClient.shared.fetchChildren()
            
            // If backend is empty (no kids paired/created), nothing to sync yet
            guard let firstApiChild = apiChildren.first else {
                print("AppSync: No child found on backend yet.")
                return 
            }
            
            let childIdStr = firstApiChild.id
            
            // 1. Fetch Backend Data
            let rules = try await APIClient.shared.fetchRules(childId: childIdStr)
            let state = try await APIClient.shared.fetchState(childId: childIdStr)
            let apiTasks = try await APIClient.shared.fetchTasks(childId: childIdStr)
            let apiOccurrences = try await APIClient.shared.fetchOccurrences(childId: childIdStr)
            
            // 2. Map Rules
            var childRules: [ChildRule] = []
            childRules.append(ChildRule(
                id: "screen-time-limit",
                kind: .screenTimeLimit,
                icon: "sf:hourglass",
                title: "Screen Time Limit",
                detail: "\(formatMinutes(rules.dailyLimitMinutes)) per day",
                on: true
            ))
            
            if rules.downtimeEnabled {
                childRules.append(ChildRule(
                    id: "downtime",
                    kind: .downtime,
                    icon: "dark_mode",
                    title: "Downtime",
                    detail: "\(rules.downtimeStart ?? "8:00 PM") – \(rules.downtimeEnd ?? "7:00 AM")",
                    on: true
                ))
            }
            
            // 3. Map Tasks/Occurrences -> UI `ChildTask`
            var uiTasks: [ChildTask] = []
            for task in apiTasks {
                // Find today's occurrence (if generated by cron or dynamically)
                let occurrence = apiOccurrences.first(where: { $0.taskId == task.id })
                
                let uiState: TaskState
                if let occ = occurrence {
                    switch occ.status {
                    case "approved": uiState = .done
                    case "submitted": uiState = .review
                    case "rejected": uiState = .pending // Or an explicit rejected state if UI supports
                    default: uiState = .pending
                    }
                } else {
                    uiState = .pending
                }
                
                uiTasks.append(ChildTask(
                    id: task.id,
                    occurrenceId: occurrence?.id,
                    title: task.title,
                    state: uiState,
                    category: task.bucket,
                    description: task.instructions ?? "",
                    note: occurrence?.bypassNote,
                    dueDate: nil, // MVP: Treat all as today unless it's an advanced scheduled task
                    photoCount: task.submissionKind == "photo" ? 1 : 0,
                    repeats: task.recurrence
                ))
            }
            
            // 4. Update Session, FamilyStore, & TaskStore
            SessionManager.shared.activeChildId = childIdStr
            TaskStore.binding(for: childIdStr).wrappedValue = uiTasks
            
            // Check if the actual child is already in FamilyStore
            if let existingChild = FamilyStore.children.first(where: { $0.id == childIdStr }) {
                existingChild.name = firstApiChild.name
                existingChild.rules = childRules
                existingChild.dailyLimitMin = rules.dailyLimitMinutes
                existingChild.manualLock = state.manualLock
            } else {
                // Remove the mock "liam" if it exists, or just clear the list if we only support one kid for MVP
                FamilyStore.children.removeAll()
                
                FamilyStore.children.append(Child(
                    id: childIdStr, name: firstApiChild.name, age: 10, dailyLimitMin: rules.dailyLimitMinutes,
                    color: FamilyStore.childColorPalette[0], manualLock: state.manualLock, taskGateOverride: state.taskGateOverride,
                    timeLeft: formatMinutes(rules.dailyLimitMinutes), timePct: 100, usageTodayMin: 0,
                    subtitle: "No tasks yet",
                    devices: FamilyStore.demoDevice(firstApiChild.name)
                ))
            }
            
            print("AppSync: Successfully synced backend data into UI state!")
            
        } catch {
            print("AppSync Failed: \(error.localizedDescription)")
        }
    }
}
